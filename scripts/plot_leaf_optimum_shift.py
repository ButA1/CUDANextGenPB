PANEL_TEMPLATE = r"""
\nextgroupplot[ylabel={YLABEL}, ymin=YMIN, ymax=YMAX, legend columns=LEGCOLS, legend to name=LEGNAME]
SERIESMINIMA"""

SERIES_TEMPLATE = r"""  \addplot[color=COLOR, mark=MARK, mark size=1.3pt, line width=0.9pt]
    table[x=sleaf, y=YCOL, discard if not={FILTCOL}{FILTVAL}] {figures/data/DATFILE.dat};
  \addlegendentry{ENTRY}
"""

# One overlay per panel rather than per series: it is the WALK of the minima that
# the figure is about, and a single marker style makes that read as one object.
MINIMA_TEMPLATE = r"""  \addplot[only marks, mark=o, mark size=3.6pt, line width=0.9pt,
           color=black!75, forget plot] coordinates {COORDS};
"""


def build_panel(series, ylabel, ycol, filtcol, datfile, legname, ylo, yhi,
                minima, legcols):
    body = []
    for i, (value, entry) in enumerate(series):
        colour, _ = RAMP[i % len(RAMP)]
        body.append(SERIES_TEMPLATE
                    .replace("COLOR", colour)
                    .replace("MARK", MARKS[i % len(MARKS)])
                    .replace("YCOL", ycol)
                    .replace("FILTCOL", filtcol)
                    .replace("FILTVAL", str(value))
                    .replace("DATFILE", datfile)
                    .replace("ENTRY", entry))
    coords = " ".join("({:g},{:.6g})".format(x, y) for x, y in minima)
    return (PANEL_TEMPLATE
            .replace("YLABEL", ylabel)
            .replace("YMIN", "{:.6g}".format(ylo))
            .replace("YMAX", "{:.6g}".format(yhi))
            .replace("LEGCOLS", str(legcols))
            .replace("LEGNAME", legname)
            .replace("SERIES", "".join(body))
            .replace("MINIMA", MINIMA_TEMPLATE.replace("COORDS", coords)))


