#!/usr/bin/env python3
r"""
Show that the optimal SOURCE leaf size moves with p, and only weakly with theta.

This is the figure behind the correction to the "both leaf sizes should be equal"
reading. The two trees are not symmetric knobs: the source leaf bounds the box
radius the MAC tests against (near-field P2P work) while the target leaf sets the
target box count (M2L pair count). Raising p makes each M2L dearer without
touching the tree geometry at all -- fmm_build_atom_tree uses p only for
comp_of(p) -- so the balance point moves toward fewer, larger source boxes. That
prediction is what the left panel tests.

    left panel   x = source leaf, one line per multipole order p
                 the minimum of each line walks RIGHT as p grows
    right panel  x = source leaf, one line per theta, each normalized to its own
                 minimum, so the shape can be compared across a 4x range in
                 absolute time. Theta changes how SHARP the optimum is; it barely
                 moves WHERE it is.

Both panels hold the target leaf fixed -- with both leaf axes free the minimum
runs along s*t ~ const and neither panel would show a clean interior optimum.

Takes several CSVs per panel because the p range was measured in two runs
(leaf_vs_p_low.csv for p=6..8, leaf_vs_p.csv for p=9..11); they are concatenated.

Writes, relative to the thesis directory:
    figures/data/<tag>_p.dat        one row per (p, source leaf)
    figures/data/<tag>_theta.dat    one row per (theta, source leaf)
    figures/data/<tag>_ref.tex      caption values as macros
    figures/<tag>.tex               the figure
    figures/<tag>_table.tex         the argmin table, \input-able separately

Sibling of plot_leaf_sweep.py (which sweeps the two leaf axes against each other
at fixed p and theta); this one holds the target leaf fixed and sweeps p and
theta instead. Shares the CSV layer, fmm_csv.py.
"""

import argparse
import os
import re
import statistics
import sys

import fmm_csv

# Same ramp as plot_leaf_sweep.py, for the same reason: ordered by lightness so
# the lines stay separable in greyscale and under the common CVD types.
RAMP = [
    ("shiftA", "1B3A6B"),
    ("shiftB", "1F77B4"),
    ("shiftC", "17A398"),
    ("shiftD", "7EA83D"),
    ("shiftE", "E8A33D"),
    ("shiftF", "C1272D"),
]
MARKS = ["*", "square*", "triangle*", "diamond*", "pentagon*", "oplus*"]

SHIFT_MACROS = ["shiftMolecule", "shiftNatoms", "shiftMac", "shiftOrder",
                "shiftTgt", "shiftRepeats", "shiftMachine"]


def localise(text, tag):
    r"""Make macros, labels and legend names unique to this figure.

    \def is global and more than one of these figures can appear in one
    document, so shared names would have every caption read whichever figure was
    typeset last. Same treatment as plot_leaf_sweep.py.
    """
    sfx = "".join(c for c in tag if c.isalpha())
    # (?![A-Za-z]) is load-bearing: a LaTeX control sequence ends at the
    # first non-letter, so a plain replace of \\leafMac also rewrites the
    # \\leafMachine that starts with it -- which it did, silently producing
    # \\leafMacleafsweepvybhine and an undefined macro in the caption.
    for name in SHIFT_MACROS:
        text = re.sub(r"\\" + name + r"(?![A-Za-z])",
                      "\\\\" + name + sfx, text)
    return text.replace("SFX", sfx).replace("TAG", tag)


def load_points(paths, stat):
    """Aggregate several replay CSVs into one point list."""
    rows = []
    for p in paths:
        if not os.path.exists(p):
            sys.exit("no such CSV: {}".format(p))
        rows.extend(fmm_csv.load(p))
    if not rows:
        sys.exit("no usable rows in {}".format(", ".join(paths)))
    points, info = fmm_csv.aggregate(rows, require_baseline=False, stat=stat)
    if not points:
        sys.exit("no energy_method=2 rows in {}".format(", ".join(paths)))
    return points, info


def hold_fixed(points, key, wanted, label):
    """Reduce to one value of an axis this figure holds fixed."""
    present = sorted({d[key] for d in points})
    if wanted is not None:
        chosen = type(present[0])(wanted)
        if chosen not in present:
            sys.exit("no rows with {} = {} (have {})".format(
                label, wanted, ", ".join("{:g}".format(v) for v in present)))
        return [d for d in points if d[key] == chosen], chosen
    if len(present) > 1:
        sys.exit("CSV carries {} values of {} ({}) -- this figure holds it "
                 "fixed, so pass --{} to choose".format(
                     len(present), label,
                     ", ".join("{:g}".format(v) for v in present), label))
    return points, present[0]


