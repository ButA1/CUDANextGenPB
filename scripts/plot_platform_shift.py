PANEL_TEMPLATE = r"""
\nextgroupplot[xlabel={$n_{leaf,AXIS}$}, xtick={XTICKS}, xticklabels={XTICKS}, ymin=YMIN, ymax=YMAX, legend columns=LEGCOLS, legend to name=LEGNAME]
SERIESMINIMA"""

SERIES_TEMPLATE = r"""  \addplot[color=COLOR, mark=MARK, mark size=1.3pt, line width=0.9pt]
    table[x=x, y=tnorm, discard if not={sid}{SID}] {figures/data/DATFILE.dat};
ENTRY"""

MINIMA_TEMPLATE = r"""  \addplot[only marks, mark=o, mark size=3.6pt, line width=0.9pt,
           color=black!75, forget plot] coordinates {COORDS};
"""


def build_panel(axis, series, datfile, xs, legname, legend, ylo, yhi, minima):
    body = []
    for sid, (label, _) in enumerate(series):
        colour, _ = RAMP[sid % len(RAMP)]
        body.append(SERIES_TEMPLATE
                    .replace("COLOR", colour)
                    .replace("MARK", MARKS[sid % len(MARKS)])
                    .replace("SID", str(sid))
                    .replace("DATFILE", datfile)
                    .replace("ENTRY",
                             "  \\addlegendentry{%s}\n" % label if legend else ""))
    coords = " ".join("({:g},{:.6g})".format(x, y) for x, y in minima)
    return (PANEL_TEMPLATE
            .replace("AXIS", axis)
            .replace("XTICKS", ",".join(str(x) for x in xs))
            .replace("YMIN", "{:.6g}".format(ylo))
            .replace("YMAX", "{:.6g}".format(yhi))
            .replace("LEGCOLS", str(min(len(series), 3)))
            .replace("LEGNAME", legname if legend else "platlegendunusedSFX")
            .replace("SERIES", "".join(body))
            .replace("MINIMA", MINIMA_TEMPLATE.replace("COORDS", coords)))


TABLE_TEMPLATE = r"""% ------------------------------------------------------------------------
%  Generated by scripts/plot_platform_shift.py -- regenerate rather than edit.
%  Include with \input{figures/TAG_table}
%  Needs \usepackage{booktabs}.
% ------------------------------------------------------------------------
\begin{table}[!htb]
\centering
\footnotesize
\caption[Leaf optimum by platform]{\textbf{The fastest leaf pair on
    \platMolecule{} over the whole $4 \times 6$ grid, for each platform, at
    $\theta = \platMac{}$ and $P = \platOrder{}$.} \emph{runner-up} is how much
    slower the second-best pair is, and \emph{spread} the widest
    repeat-to-repeat variation in that series.\platMachine}
\label{tab:TAG}
\begin{tabular}{lrrrrr}
\toprule
platform & $n_{leaf,src}$ & $n_{leaf,tgt}$ & time [s] & runner-up & spread \\
\midrule
ROWS
\bottomrule
\end{tabular}
\end{table}
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("series", nargs="+",
                    help="LABEL=path/to/leaf_sweep.csv, in the order they should "
                         "be drawn; the design expects local-4r, A100-4r, A100-16r")
    ap.add_argument("--thesis", default="thesis")
    ap.add_argument("--tag", default="platform_shift")
    ap.add_argument("--fixed-tgt", type=int, default=None,
                    help="hold ALL series' left panel at this target leaf. "
                         "Default is to slice each series through its OWN "
                         "optimum -- a shared slice is not neutral here, because "
                         "the two knobs trade along s*t and a slice taken at one "
                         "platform's optimum lands on another's flat region")
    ap.add_argument("--fixed-src", type=int, default=None,
                    help="hold ALL series' right panel at this source leaf, as above")
    ap.add_argument("--molecule", default=None)
    ap.add_argument("--natoms", default=None)
    fmm_csv.add_machine_argument(ap)
    ap.add_argument("--stat", default="median",
                    choices=sorted(fmm_csv.TIME_STATS))
    args = ap.parse_args()

    loaded = [load_series(s, args.stat) for s in args.series]
    if len(loaded) < 2:
        sys.exit("need at least two series to compare")

    macs = {d["mac"] for _, g, _ in loaded for d in g.values()}
    orders = {d["p"] for _, g, _ in loaded for d in g.values()}
    if len(macs) != 1 or len(orders) != 1:
        sys.exit("the series disagree on theta (%s) or p (%s) -- this figure "
                 "holds both fixed" % (sorted(macs), sorted(orders)))
    mac, order = macs.pop(), orders.pop()

    def best_of(grid):
        return min(grid, key=lambda k: grid[k]["time"])

    # Per-series slice unless told otherwise: each curve is the profile through
    # that platform's OWN grid optimum, which is the operating point anyone would
    # actually run it at. A single shared slice reproduces whichever platform it
    # was taken from and reads as noise on the others.
    fixed = [(args.fixed_tgt or best_of(g)[1], args.fixed_src or best_of(g)[0])
             for _, g, _ in loaded]

    src_prof = [("%s (tgt %d)" % (lab, fx[0]), profile(g, "src", fx[0]))
                for (lab, g, _), fx in zip(loaded, fixed)]
    tgt_prof = [("%s (src %d)" % (lab, fx[1]), profile(g, "tgt", fx[1]))
                for (lab, g, _), fx in zip(loaded, fixed)]
    fixed_tgt = fixed[0][0]
    fixed_src = fixed[0][1]
    for name, prof in (("source", src_prof), ("target", tgt_prof)):
        for lab, rows in prof:
            if not rows:
                sys.exit("series %r has no %s-axis rows at the fixed value" %
                         (lab, name))

    data_dir = os.path.join(args.thesis, "figures", "data")
    os.makedirs(data_dir, exist_ok=True)
    src_dat = os.path.join(data_dir, args.tag + "_src.dat")
    tgt_dat = os.path.join(data_dir, args.tag + "_tgt.dat")
    reftex = os.path.join(data_dir, args.tag + "_ref.tex")
    fig = os.path.join(args.thesis, "figures", args.tag + ".tex")
    tab = os.path.join(args.thesis, "figures", args.tag + "_table.tex")

    for path, prof in ((src_dat, src_prof), (tgt_dat, tgt_prof)):
        with open(path, "w") as fh:
            fh.write("sid x tnorm time\n")
            for sid, (_, rows) in enumerate(prof):
                for x, tnorm, t in rows:
                    fh.write("{} {} {:.6g} {:.6g}\n".format(sid, x, tnorm, t))

    src_xs = sorted({x for _, rows in src_prof for x, _, _ in rows})
    tgt_xs = sorted({x for _, rows in tgt_prof for x, _, _ in rows})
    src_min = [min(rows, key=lambda r: r[1])[:2] for _, rows in src_prof]
    tgt_min = [min(rows, key=lambda r: r[1])[:2] for _, rows in tgt_prof]

    def span(prof):
        v = [t for _, rows in prof for _, t, _ in rows]
        pad = 0.08 * (max(v) - min(v))
        return min(v) - pad, max(v) + pad

    slo, shi = span(src_prof)
    tlo, thi = span(tgt_prof)

    # Each panel gets its OWN legend: the entries carry the value the other axis
    # is held at, and that differs between the panels, so one shared legend would
    # label the right-hand panel with the left-hand panel's slices.
    panels = (build_panel("src", src_prof, args.tag + "_src", src_xs,
                          "platlegendsrcSFX", True, slo, shi, src_min)
              + build_panel("tgt", tgt_prof, args.tag + "_tgt", tgt_xs,
                            "platlegendtgtSFX", True, tlo, thi, tgt_min))

    molecule = args.molecule or os.path.splitext(loaded[0][2]["molecule"])[0] or "?"
    nrep = int(statistics.median(d["n"] for _, g, _ in loaded for d in g.values()))
    ranks = {info["ranks"] for _, _, info in loaded}

    ref_buf = [
        "% generated by scripts/plot_platform_shift.py -- do not edit\n",
        "\\def\\platMolecule{%s}\n" % molecule,
        "\\def\\platNatoms{%s}\n" % (args.natoms or loaded[0][2]["natoms"] or "?"),
        "\\def\\platMac{%g}\n" % mac,
        "\\def\\platOrder{%d}\n" % order,
        "\\def\\platFixedTgt{%d}\n" % fixed_tgt,
        "\\def\\platFixedSrc{%d}\n" % fixed_src,
        "\\def\\platRepeats{%d}\n" % nrep,
        # The rank count differs BETWEEN series here -- that is the point of the
        # figure -- so the shared note would be wrong. Each series names its own.
        "\\def\\platMachine{%s}\n" % (
            fmm_csv.machine_note(args.machine, None).replace(
                "; the rank count is not recorded in the source CSV",
                "; each series names its own rank count")
            if len(ranks) > 1
            else fmm_csv.machine_note(args.machine, ranks.pop())),
    ]
    with open(reftex, "w") as fh:
        fh.write(localise("".join(ref_buf), args.tag))

    colordefs = "\n".join("\\definecolor{%s}{HTML}{%s}" % (n, h)
                          for n, h in RAMP[:len(loaded)])
    with open(fig, "w") as fh:
        fh.write(localise(FIGURE_TEMPLATE
                          .replace("COLORDEFS", colordefs)
                          .replace("PANELS", panels), args.tag))

    rows = []
    print("grid-wide optimum per platform:")
    for lab, grid, info in loaded:
        ordered = sorted(grid.values(), key=lambda d: d["time"])
        b, second = ordered[0], ordered[1]
        margin = second["time"] / b["time"] - 1.0
        sp = info["spread"]
        rows.append("%s & %d & %d & %.3f & %.1f\\%% & %s \\\\\n"
                    % (lab, b["sleaf"], b["tleaf"], b["time"], 100 * margin,
                       "---" if sp is None else "%.1f\\%%" % (100 * sp)))
        print("   %-28s %3d/%-5d %7.3f s   runner-up %d/%d +%.1f%%"
              % (lab, b["sleaf"], b["tleaf"], b["time"],
                 second["sleaf"], second["tleaf"], 100 * margin))
    with open(tab, "w") as fh:
        fh.write(localise(TABLE_TEMPLATE.replace("ROWS", "".join(rows)), args.tag))

    print("\nleft panel  : source axis at fixed tgt = %d" % fixed_tgt)
    for (lab, _), (x, y) in zip(src_prof, src_min):
        print("   %-28s min at src %d" % (lab, x))
    print("right panel : target axis at fixed src = %d" % fixed_src)
    for (lab, _), (x, y) in zip(tgt_prof, tgt_min):
        print("   %-28s min at tgt %d" % (lab, x))
    print("\nwrote %s\n      %s\n      %s\n      %s\n      %s"
          % (src_dat, tgt_dat, reftex, fig, tab))


if __name__ == "__main__":
    sys.exit(main())
