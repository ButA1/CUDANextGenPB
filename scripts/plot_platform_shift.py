#!/usr/bin/env python3
r"""
Separate the two things that move the leaf optimum: the GPU and the rank count.

Every cluster-vs-local comparison so far changed both at once (4 ranks on an
RTX 3080 against 16 on an A100), so neither effect could be attributed. With a
4-rank run on the A100 as the pivot, the two are separable:

    local 4r  ->  A100 4r      only the GPU changed
    A100 4r   ->  A100 16r     only the rank count changed

and the two trees respond differently, which is a structural property rather
than a coincidence: the SOURCE tree is built from the atoms, which every rank
holds a full copy of, so the rank count cannot reach it. The TARGET tree is
built from this rank's share of the surface points, so the rank count sets its
size directly.

    left panel   x = source leaf at a fixed target leaf
    right panel  x = target leaf at a fixed source leaf

Each line is normalised to its own minimum, because the three configurations
differ by up to 3.5x in absolute time and the subject here is the SHAPE -- where
each curve bottoms out, not how high it sits.

Writes, relative to the thesis directory:
    figures/data/<tag>_src.dat    one row per (series, source leaf)
    figures/data/<tag>_tgt.dat    one row per (series, target leaf)
    figures/data/<tag>_ref.tex    caption values as macros
    figures/<tag>.tex             the figure
    figures/<tag>_table.tex       the grid-wide optimum of each series

Sibling of plot_leaf_optimum_shift.py, which holds the platform fixed and sweeps
p and theta; this one holds p and theta fixed and varies the platform.
"""

import argparse
import os
import re
import statistics
import sys

import fmm_csv

# Three series is the design point (local 4r / A100 4r / A100 16r). The ramp
# runs cool-to-warm so it survives greyscale, and the first two -- the pair that
# differs only in GPU -- are the two blues, so the eye groups them.
RAMP = [
    ("platA", "1B3A6B"),
    ("platB", "1F77B4"),
    ("platC", "D95F02"),
    ("platD", "7EA83D"),
]
MARKS = ["*", "square*", "triangle*", "diamond*"]

PLAT_MACROS = ["platMolecule", "platNatoms", "platMac", "platOrder",
               "platFixedTgt", "platFixedSrc", "platRepeats", "platMachine"]


def localise(text, tag):
    r"""Suffix this figure's macros and labels so several can coexist."""
    sfx = "".join(c for c in tag if c.isalpha())
    # (?![A-Za-z]) because a control sequence ends at the first non-letter:
    # without it \platMac would also rewrite the \platMachine that starts with it.
    for name in PLAT_MACROS:
        text = re.sub(r"\\" + name + r"(?![A-Za-z])", "\\\\" + name + sfx, text)
    return text.replace("SFX", sfx).replace("TAG", tag)


def load_series(spec, stat):
    """"LABEL=path" -> (label, {(sleaf, tleaf): time}, info)."""
    if "=" not in spec:
        sys.exit("series must be LABEL=path/to/leaf_sweep.csv, got %r" % spec)
    label, path = spec.split("=", 1)
    if not os.path.exists(path):
        sys.exit("no such CSV: %s" % path)
    rows = fmm_csv.load(path)
    points, info = fmm_csv.aggregate(rows, require_baseline=False, stat=stat)
    if not points:
        sys.exit("no energy_method=2 rows in %s" % path)
    grid = {(d["sleaf"], d["tleaf"]): d for d in points}

    # Widest repeat-to-repeat variation anywhere in this grid. The table reports
    # it so a 0.3% runner-up margin can be read against the noise it sits in.
    by_cfg = {}
    for r in rows:
        if r.get("energy_method") != "2":
            continue
        k = (r["fmm_mac"], r["fmm_multipole_order"], r["fmm_leaf_size"],
             r.get("fmm_target_leaf_size"))
        by_cfg.setdefault(k, []).append(float(r["t_energy"]))
    spreads = [(max(v) - min(v)) / statistics.median(v)
               for v in by_cfg.values() if len(v) > 1]
    info["spread"] = max(spreads) if spreads else None
    return label.strip(), grid, info


def profile(grid, axis, fixed_other):
    """Normalised slice through the grid: [(x, time/min)] along `axis`."""
    if axis == "src":
        pts = {s: d for (s, t), d in grid.items() if t == fixed_other}
    else:
        pts = {t: d for (s, t), d in grid.items() if s == fixed_other}
    if not pts:
        return []
    lo = min(d["time"] for d in pts.values())
    return sorted((x, d["time"] / lo, d["time"]) for x, d in pts.items())


